<div id="info-boxes" class="mb-4">
	<details class="mb-3">
		<summary class="fs-5 text-navy"> What you can use the rankings for? </summary>
		<div class="py-4">
			<p>You can use the rankings to:</p>
			<ul class="tick-list">
				<li>Compare areas to see which are more or less deprived</li>
				<li>Find the most and least deprived areas</li>
				<li>Look at patterns across places to see where deprivation is highest or lowest</li>
				<li>
					See how areas change over time, including which areas move in or out of the most deprived
					group
				</li>
			</ul>
			<p>
				You can do this for Northern Ireland as a whole, for each Local Government District, or for
				other large areas.
			</p>
		</div>
	</details>
	<details class="mb-3">
		<summary class="fs-5 text-navy"> What you should not use the rankings for? </summary>
		<div class="py-4">
			<p>You should not use the rankings to:</p>
			<ul class="x-list">
				<li>Identify deprived people or groups – they describe areas, not individuals</li>
				<li>
					Measure how deprived an area is in absolute terms – they only rank areas against each
					other
				</li>
				<li>
					Say how much more deprived one area is than another – they only show order, not size of
					difference
				</li>
				<li>
					Track changes in absolute deprivation over time – they show a point in time, not change in
					level
				</li>
				<li>
					Measure wealth or affluence – not being deprived does not always mean being well off
				</li>
				<li>Compare with other UK countries – each country uses different data and methods</li>
			</ul>
		</div>
	</details>
	<details class="mb-3">
		<summary class="fs-5 text-navy">
			Comparing the Multiple Deprivation Measure with the individual domains
		</summary>
		<div class="py-4">
			<p>
				The seven types of deprivation each make up part of the overall measure. They are combined
				using set weights.
			</p>

			<p>
				The overall measure gives a single summary for each area. However, it can hide important
				differences between the types of deprivation.
			</p>

			<p>
				NISRA encourages you to look at both the overall measure and the individual types. This is
				especially helpful when focusing on a specific issue or when choosing ways to improve
				deprivation.
			</p>
		</div>
	</details>
</div>
